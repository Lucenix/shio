#!/usr/bin/env python3

import argparse
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


def load_csv(path: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    return df


def ensure_expected_columns(df: pd.DataFrame):
    cols = [c for c in df.columns if c != "timestamp"]
    if len(cols) % 2 != 0 or "timestamp" not in df.columns:
        raise ValueError(
            f"Expected 'timestamp' as a column and an even number of bandwidth columns after 'timestamp', got {len(cols)}. "
            "The expected format is: timestamp, nodeX_data, nodeX_metadata, ..."
        )

def assemble_full_replayed_df(replayer_df: pd.DataFrame) -> pd.DataFrame:
    """Build one full timeseries dataframe from a replayer CSV.

    Each row in the replayer file points to a per-node CSV containing
    timestamp,data,metadata and a start timestamp offset. We read each file,
    shift its timestamps by the offset, rename the data/metadata columns to
    the node-specific names, and combine every node into a single dataframe.
    """
    if {"start_timestamp", "stats_timeseries_file"}.difference(replayer_df.columns):
        raise ValueError("Replayer CSV must contain 'start_timestamp' and 'stats_timeseries_file' columns.")

    frames = []
    for idx, row in enumerate(replayer_df.sort_values("start_timestamp").itertuples(index=False)):
        csv_path = Path(row.stats_timeseries_file)
        if not csv_path.is_absolute():
            raise ValueError(f"stats_timeseries_file must be an absolute path: {csv_path}")
        if not csv_path.exists():
            raise FileNotFoundError(f"Missing stats_timeseries_file: {csv_path}")

        node_df = load_csv(str(csv_path)).copy()
        if "timestamp" not in node_df.columns:
            raise ValueError(f"CSV does not contain a 'timestamp' column: {csv_path}")

        node_df["timestamp"] = pd.to_numeric(node_df["timestamp"], errors="coerce").fillna(0).astype(int)
        node_df["timestamp"] += int(row.start_timestamp)

        node_df = node_df.rename(columns={
            c: f"n{idx}_{c}" for c in node_df.columns if c != "timestamp"
        })
        frames.append(node_df)

    if not frames:
        return pd.DataFrame(columns=["timestamp"])

    full_df = frames[0]
    for next_df in frames[1:]:
        full_df = full_df.merge(next_df, on="timestamp", how="outer")

    full_df = full_df.sort_values("timestamp").reset_index(drop=True)
    for col in [c for c in full_df.columns if c != "timestamp"]:
        full_df[col] = pd.to_numeric(full_df[col], errors="coerce").fillna(0).astype(int)
    return full_df

def parse_runtime_inputs(df: pd.DataFrame):
    cols = [c for c in df.columns if c != "timestamp"]
    pairs = []
    for i in range(0, len(cols), 2):
        data_col = cols[i]
        meta_col = cols[i + 1]
        pairs.append((data_col, meta_col))
    return pairs

def main():
    parser = argparse.ArgumentParser(description="Plot requested vs enforced bandwidth CSVs.")
    parser.add_argument("input_csv", help="Original CSV with requested bandwidths OR replayer file to create plot from")
    parser.add_argument("--output_csv", type=str, default=None, help="Enforced-bandwidth CSV generated by the simulator (optional)")
    parser.add_argument("--truncate-end", action="store_true", help="Truncate both series at the end timestamp of the original input CSV")
    parser.add_argument("--output-prefix", default="bandwidth_comparison", help="Output prefix for generated plots (default: bandwidth_comparison)")
    parser.add_argument("--horizontal-size-factor", type=float, default=1, help="Number of inches between each minute in the figure (default: 1)")
    args = parser.parse_args()

    df_input = load_csv(args.input_csv)
    if "stats_timeseries_file" in df_input.columns:
        df_input = assemble_full_replayed_df(df_input)
    else:
        ensure_expected_columns(df_input)
    df_input["timestamp"] /= 60

    df_output = pd.DataFrame()

    if args.output_csv:
        df_output = load_csv(args.output_csv)
        ensure_expected_columns(df_output)
        df_output["timestamp"] /= 60
        output_dir = Path(args.output_csv).resolve().parent.parent
        base_name = Path(args.output_csv).stem
    else:
        output_dir = Path(args.input_csv).resolve().parent.parent
        base_name = Path(args.input_csv).stem
    
    meta_plot = output_dir / "plots" / f"{base_name}_metadata_comparison.png"
    data_plot = output_dir / "plots" / f"{base_name}_data_comparison.png"

    # Metadata plot
    pairs = parse_runtime_inputs(df_input)
    if args.output_csv:
        out_pairs = parse_runtime_inputs(df_output)
        xticks = np.arange(min(df_output["timestamp"]), max(df_output["timestamp"]) + 1, 1)
    else:
        out_pairs = pairs
        xticks = np.arange(min(df_input["timestamp"]), max(df_input["timestamp"]) + 1, 1)
    fig, axes = plt.subplots(len(pairs), 1, figsize=(len(xticks) * args.horizontal_size_factor, 4 * len(pairs)), squeeze=False)
    axes = axes.flatten()

    if args.truncate_end and not df_output.empty:
        max_ts = df_input["timestamp"].iloc[-1]
        #df_input = df_input[df_input["timestamp"] <= max_ts].copy()
        df_output = df_output[df_output["timestamp"] <= max_ts].copy()

