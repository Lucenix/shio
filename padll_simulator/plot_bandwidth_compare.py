#!/usr/bin/env python3

import argparse
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


def load_csv(path: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    if "timestamp" not in df.columns:
        raise ValueError(f"CSV does not contain a 'timestamp' column: {path}")
    return df


def ensure_expected_columns(df: pd.DataFrame):
    cols = [c for c in df.columns if c != "timestamp"]
    if len(cols) % 2 != 0:
        raise ValueError(
            f"Expected an even number of bandwidth columns after 'timestamp', got {len(cols)}. "
            "The expected format is: timestamp, nodeX_data, nodeX_metadata, ..."
        )


def parse_runtime_inputs(df: pd.DataFrame):
    cols = [c for c in df.columns if c != "timestamp"]
    pairs = []
    for i in range(0, len(cols), 2):
        data_col = cols[i]
        meta_col = cols[i + 1]
        pairs.append((data_col, meta_col))
    return pairs

def main():
    parser = argparse.ArgumentParser(description="Plot requested vs enforced bandwidth CSVs.")
    parser.add_argument("input_csv", help="Original CSV with requested bandwidths")
    parser.add_argument("output_csv", help="Enforced-bandwidth CSV generated by the simulator")
    parser.add_argument("--truncate-end", action="store_true", help="Truncate both series at the end timestamp of the original input CSV")
    parser.add_argument("--output-prefix", default="bandwidth_comparison", help="Output prefix for generated plots (default: bandwidth_comparison)")
    parser.add_argument("--horizontal-size-factor", type=float, default=1, help="Number of inches between each minute in the figure (default: 1)")
    args = parser.parse_args()

    df_input = load_csv(args.input_csv)
    df_output = load_csv(args.output_csv)
    ensure_expected_columns(df_input)
    ensure_expected_columns(df_output)
    df_input["timestamp"] /= 60
    df_output["timestamp"] /= 60

    output_dir = Path(args.output_csv).resolve().parent
    base_name = Path(args.output_csv).stem

    meta_plot = output_dir / "plots" / f"{base_name}_metadata_comparison.png"
    data_plot = output_dir / "plots" / f"{base_name}_data_comparison.png"

    # Metadata plot
    pairs = parse_runtime_inputs(df_input)
    out_pairs = parse_runtime_inputs(df_output)
    xticks = np.arange(min(df_output["timestamp"]), max(df_output["timestamp"]) + 1, 1)
    fig, axes = plt.subplots(len(pairs), 1, figsize=(len(xticks) * args.horizontal_size_factor, 4 * len(pairs)), squeeze=False)
    axes = axes.flatten()
    if len(pairs) != len(out_pairs):
        raise ValueError("Input and output CSVs do not contain the same number of node pairs.")

    if args.truncate_end:
        max_ts = df_input["timestamp"].iloc[-1]
        #df_input = df_input[df_input["timestamp"] <= max_ts].copy()
        df_output = df_output[df_output["timestamp"] <= max_ts].copy()

    for idx, ((in_data_col, in_meta_col), (out_data_col, out_meta_col)) in enumerate(zip(pairs, out_pairs)):
        ax = axes[idx]
        ax.plot(df_input["timestamp"], df_input[in_meta_col] / 1000, label=f"input {in_meta_col}", linestyle="-", marker="", alpha=0.8)
        ax.plot(df_output["timestamp"], df_output[out_meta_col] / 1000, label=f"enforced {out_meta_col}", linestyle="--", marker="", alpha=0.9)
        ax.set_title(f"Node {idx} metadata comparison")
        ax.set_xlabel("timestamp in minutes")
        ax.set_xticks(xticks)
        ax.set_xlim(df_output["timestamp"][0], df_output["timestamp"].iloc[-1] + 1)
        ax.set_ylabel("kops/s")
        ax.set_ylim(df_input[in_meta_col].min(), (df_input[in_meta_col].quantile(0.99) / 1000) + 1)
        ax.grid(True, alpha=0.3)
        ax.legend()
    fig.tight_layout()
    fig.savefig(str(meta_plot), dpi=200)
    plt.close(fig)
    print(f"Metadata plot: {meta_plot}")

